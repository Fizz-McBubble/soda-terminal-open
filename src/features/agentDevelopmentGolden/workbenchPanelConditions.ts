export function workbenchPanelConditionPresentation(conditions: readonly string[]): string[] {
  const result = conditions.flatMap((condition) => {
    const source = condition.trim()
    if (!source || omitted.has(source)) return []
    const exact = wording.get(source)
    if (exact !== undefined) return typeof exact === 'string' ? [exact] : [...exact]
    for (const [pattern, render] of contextualWording) {
      const match = pattern.exec(source)
      if (match) return [render(...match.slice(1))]
    }
    return [source]
  })
  const unique = [...new Set(result)]
  if (unique.some((line) => /^达到上方回能目标，可吃满核心\d+级提供的冲击力加成。$/.test(line))) {
    const reference = unique.indexOf('6号位选能量自动回复，面板可参考2.88+。')
    if (reference >= 0) unique[reference] = '6号位选能量自动回复。'
  }
  // Prefer the current character's explicit condition over a covered generic
  // sentence. Match complete reviewed clauses, never arbitrary keywords.
  const covered = new Set<string>()
  if (
    unique.some((line) =>
      /^开启并保持「巡空枪势」，面板暴击率达到核心\d+级的目标即可满暴。$/.test(line),
    )
  ) {
    covered.add('满核心时，面板暴击率达到34%，开启「巡空枪势」即可满暴。')
    covered.add('需触发并保持巡空枪势。')
  }
  if (
    unique.some((line) =>
      /^攻击力目标按当前核心\d+级计算；普通展旗上限500点攻击，消耗涡流时上限1000，初始攻击目标相同。$/.test(
        line,
      ),
    )
  ) {
    covered.add('攻击力目标随当前核心技等级变化。')
  }
  if (
    unique.some((line) =>
      /^攻击力目标按当前有效特殊技\d+级、600点全队攻击增益上限计算。$/.test(line),
    )
  ) {
    covered.add('攻击力目标随当前特殊技等级变化。')
  }
  if (unique.includes('局外暴击率需先达到55%，叠加核心被动的25%后触发能力。')) {
    covered.add('暴击率参考包含核心被动。')
  }
  if (unique.includes('若使用「山大王」，暴击率需达到 50%；攻击力战斗内还会提高。')) {
    covered.add('使用「山大王」四件套时，暴击率需达到50%。')
  }
  return unique.filter((line) => !covered.has(line))
}
